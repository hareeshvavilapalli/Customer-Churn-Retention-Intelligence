USE customer_churn_db;

-- ------------------------------------------------------------------------------
-- QUERY 14: Monthly Recurring Revenue (MRR) & Revenue Lost to Churn
-- ------------------------------------------------------------------------------
-- Business Question:
-- What is the total Monthly Recurring Revenue (MRR) across the customer portfolio,
-- how much MRR is retained, and how much is actively lost to departing subscribers?
--
-- Explanation of Logic:
-- Uses conditional aggregation on `MonthlyCharges` by `Churn` to compute total MRR,
-- retained MRR, churned MRR, and the percentage of portfolio monthly revenue lost.

SELECT 
    ROUND(SUM(MonthlyCharges), 2) AS total_portfolio_mrr,
    ROUND(SUM(CASE WHEN Churn = 'No' THEN MonthlyCharges ELSE 0 END), 2) AS retained_mrr,
    ROUND(SUM(CASE WHEN Churn = 'Yes' THEN MonthlyCharges ELSE 0 END), 2) AS lost_churned_mrr,
    ROUND(SUM(CASE WHEN Churn = 'Yes' THEN MonthlyCharges ELSE 0 END) * 100.0 / SUM(MonthlyCharges), 2) AS lost_mrr_pct
FROM customers;

-- Expected Business Insight:
-- Total company MRR stands at $456,116.60. Active churn accounts for $139,130.85 per month
-- (30.50% of all monthly recurring revenue). This proves churn is disproportionately concentrated
-- in higher-billing accounts (30.50% revenue lost vs 26.54% customer volume lost).


-- ------------------------------------------------------------------------------
-- QUERY 15: Customer Lifetime Value (LTV) & Total Cumulative Revenue
-- ------------------------------------------------------------------------------
-- Business Question:
-- What is the total cumulative lifetime revenue generated by the portfolio, and how does
-- historical revenue differ between retained accounts and departed accounts?
--
-- Explanation of Logic:
-- Groups by `Churn` and computes total cumulative `TotalCharges`, average lifetime spend (LTV),
-- minimum charge, and maximum charge.

SELECT 
    Churn,
    COUNT(*) AS customer_count,
    ROUND(SUM(TotalCharges), 2) AS total_cumulative_revenue,
    ROUND(AVG(TotalCharges), 2) AS avg_lifetime_value,
    ROUND(MIN(TotalCharges), 2) AS min_total_charges,
    ROUND(MAX(TotalCharges), 2) AS max_total_charges
FROM customers
GROUP BY Churn;

-- Expected Business Insight:
-- Retained customers contribute $13,193,241.80 with an average lifetime value of $2,549.91.
-- Churned customers generated $2,862,926.90 with an average LTV of only $1,531.80—a 40% reduction
-- in lifetime revenue per account due to premature contract termination.


-- ------------------------------------------------------------------------------
-- QUERY 16: Average Monthly Charges (ARPU) Disparity across Contracts
-- ------------------------------------------------------------------------------
-- Business Question:
-- Do churned customers pay higher monthly fees than retained customers across all contract types?
--
-- Explanation of Logic:
-- Computes the average `MonthlyCharges` for retained and churned cohorts within each contract term,
-- determining the fee disparity (delta).

SELECT 
    Contract,
    ROUND(AVG(CASE WHEN Churn = 'No' THEN MonthlyCharges END), 2) AS avg_monthly_retained,
    ROUND(AVG(CASE WHEN Churn = 'Yes' THEN MonthlyCharges END), 2) AS avg_monthly_churned,
    ROUND(AVG(CASE WHEN Churn = 'Yes' THEN MonthlyCharges END) - AVG(CASE WHEN Churn = 'No' THEN MonthlyCharges END), 2) AS monthly_fee_delta
FROM customers
GROUP BY Contract
ORDER BY Contract;

-- Expected Business Insight:
-- Churned customers pay consistently higher monthly fees across all contract types:
-- Month-to-month churners pay +$8.14/mo more ($73.02 vs $61.46);
-- One-year churners pay +$24.23/mo more ($85.06 vs $62.50);
-- Two-year churners pay +$26.31/mo more ($86.78 vs $60.03).
-- High monthly pricing is a pervasive catalyst for customer dissatisfaction and departure.


-- ------------------------------------------------------------------------------
-- QUERY 17: High-ARPU Account Churn Vulnerability (Top Quartile > $89.85/mo)
-- ------------------------------------------------------------------------------
-- Business Question:
-- What is the churn rate among premium subscribers paying in the top quartile of monthly charges
-- (MonthlyCharges >= $89.85), and how much monthly revenue is at risk?
--
-- Explanation of Logic:
-- Segments customers into 'High ARPU (Top 25%)' vs 'Standard / Low ARPU' based on the Q3 cutoff ($89.85),
-- calculating headcounts, churn counts, churn rates, and lost monthly revenue.

SELECT 
    CASE WHEN MonthlyCharges >= 89.85 THEN 'High ARPU (Top 25%)' ELSE 'Standard / Low ARPU' END AS revenue_tier,
    COUNT(*) AS customer_count,
    SUM(CASE WHEN Churn = 'Yes' THEN 1 ELSE 0 END) AS churned_count,
    ROUND(SUM(CASE WHEN Churn = 'Yes' THEN 1.0 ELSE 0.0 END) * 100.0 / COUNT(*), 2) AS churn_rate_pct,
    ROUND(SUM(MonthlyCharges), 2) AS total_tier_mrr,
    ROUND(SUM(CASE WHEN Churn = 'Yes' THEN MonthlyCharges ELSE 0 END), 2) AS lost_tier_mrr
FROM customers
GROUP BY CASE WHEN MonthlyCharges >= 89.85 THEN 'High ARPU (Top 25%)' ELSE 'Standard / Low ARPU' END;

-- Expected Business Insight:
-- The top 25% highest-paying subscribers (1,760 accounts) churn at 36.81%, compared to 23.11%
-- for standard accounts. This segment alone accounts for $66,271.70 of lost monthly revenue
-- (47.6% of the company's total lost MRR).


-- ------------------------------------------------------------------------------
-- QUERY 18: Revenue at Risk Across Tenure Cohorts
-- ------------------------------------------------------------------------------
-- Business Question:
-- How is monthly recurring revenue lost distributed across customer tenure cohorts?
--
-- Explanation of Logic:
-- Groups by `tenure_group`, computing total cohort MRR, lost cohort MRR, and the percentage
-- of cohort revenue forfeited to churn.

SELECT 
    tenure_group,
    COUNT(*) AS customer_count,
    ROUND(SUM(MonthlyCharges), 2) AS total_cohort_mrr,
    ROUND(SUM(CASE WHEN Churn = 'Yes' THEN MonthlyCharges ELSE 0 END), 2) AS lost_cohort_mrr,
    ROUND(SUM(CASE WHEN Churn = 'Yes' THEN MonthlyCharges ELSE 0 END) * 100.0 / SUM(MonthlyCharges), 2) AS pct_cohort_mrr_lost
FROM customers
GROUP BY tenure_group
ORDER BY tenure_group;

-- Expected Business Insight:
-- In the 0-12 month cohort, $75,984.75 of MRR is lost (54.6% of all lost MRR; 57.06% of the cohort's
-- billing). By Year 6 (61-72 months), monthly revenue loss drops to just $7,506.70 (6.77% of cohort MRR).


-- ------------------------------------------------------------------------------
-- QUERY 19: Revenue Exposure by Internet Service Technology
-- ------------------------------------------------------------------------------
-- Business Question:
-- What is the total and lost monthly recurring revenue across broadband technologies?
--
-- Explanation of Logic:
-- Groups by `InternetService`, aggregating customer volume, total MRR, churned MRR,
-- and the share of technology revenue lost.

SELECT 
    InternetService,
    COUNT(*) AS customer_count,
    ROUND(SUM(MonthlyCharges), 2) AS total_mrr,
    ROUND(SUM(CASE WHEN Churn = 'Yes' THEN MonthlyCharges ELSE 0 END), 2) AS lost_mrr,
    ROUND(SUM(CASE WHEN Churn = 'Yes' THEN MonthlyCharges ELSE 0 END) * 100.0 / SUM(MonthlyCharges), 2) AS pct_lost_mrr
FROM customers
GROUP BY InternetService
ORDER BY lost_mrr DESC;

-- Expected Business Insight:
-- Fiber optic internet represents an immense financial vulnerability: it generates $283,281.30
-- in monthly revenue, but loses $118,677.60/month to churn (41.90% revenue loss).
-- Fiber accounts for 85.3% of the company's total monthly lost revenue.
